-- NexFieldForce ERP and CRM extension tables. All records are tenant scoped.

CREATE TABLE IF NOT EXISTS public.suppliers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  name TEXT NOT NULL, contact_name TEXT, email TEXT, phone TEXT, address TEXT,
  status TEXT NOT NULL DEFAULT 'ACTIVE', created_by_id BIGINT, created_by_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.purchase_requisitions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  requisition_number TEXT NOT NULL, title TEXT NOT NULL, description TEXT, requested_by TEXT,
  total_amount NUMERIC(18,2) NOT NULL DEFAULT 0, status TEXT NOT NULL DEFAULT 'DRAFT',
  created_by_id BIGINT, created_by_name TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(company_id, requisition_number)
);

CREATE TABLE IF NOT EXISTS public.purchase_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  po_number TEXT NOT NULL, supplier_id BIGINT REFERENCES public.suppliers(id) ON DELETE SET NULL,
  supplier_name TEXT NOT NULL, description TEXT, total_amount NUMERIC(18,2) NOT NULL DEFAULT 0,
  expected_date DATE, status TEXT NOT NULL DEFAULT 'DRAFT', created_by_id BIGINT, created_by_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(company_id, po_number)
);

CREATE TABLE IF NOT EXISTS public.goods_receipts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  receipt_number TEXT NOT NULL, purchase_order_id BIGINT REFERENCES public.purchase_orders(id) ON DELETE SET NULL,
  reference_number TEXT NOT NULL, notes TEXT, status TEXT NOT NULL DEFAULT 'RECEIVED',
  created_by_id BIGINT, created_by_name TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(company_id, receipt_number)
);

CREATE TABLE IF NOT EXISTS public.invoices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  invoice_number TEXT NOT NULL, customer_id BIGINT REFERENCES public.customers(id) ON DELETE SET NULL,
  customer_name TEXT NOT NULL, description TEXT, due_date DATE, total_amount NUMERIC(18,2) NOT NULL DEFAULT 0,
  amount_paid NUMERIC(18,2) NOT NULL DEFAULT 0, balance_due NUMERIC(18,2) NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'DRAFT', created_by_id BIGINT, created_by_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(company_id, invoice_number)
);

CREATE TABLE IF NOT EXISTS public.support_tickets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  ticket_number TEXT, customer_id BIGINT REFERENCES public.customers(id) ON DELETE SET NULL,
  subject TEXT NOT NULL, description TEXT, category TEXT DEFAULT 'General', priority TEXT DEFAULT 'MEDIUM',
  status TEXT NOT NULL DEFAULT 'OPEN', assigned_to_id BIGINT, created_by_id BIGINT, created_by_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.projects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  name TEXT NOT NULL, description TEXT, client_name TEXT, manager_id BIGINT, budget_amount NUMERIC(18,2) NOT NULL DEFAULT 0,
  start_date DATE, end_date DATE, status TEXT NOT NULL DEFAULT 'PLANNING', created_by_id BIGINT, created_by_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.marketing_campaigns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  name TEXT NOT NULL, channel TEXT DEFAULT 'EMAIL', audience TEXT, budget_amount NUMERIC(18,2) NOT NULL DEFAULT 0,
  starts_at TIMESTAMPTZ, ends_at TIMESTAMPTZ, status TEXT NOT NULL DEFAULT 'DRAFT', created_by_id BIGINT, created_by_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.automation_workflows (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  name TEXT NOT NULL, description TEXT, trigger_event TEXT NOT NULL DEFAULT 'manual', status TEXT NOT NULL DEFAULT 'DRAFT',
  is_active BOOLEAN NOT NULL DEFAULT FALSE, created_by_id BIGINT, created_by_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.integration_connections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  provider TEXT NOT NULL, connection_name TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'DISCONNECTED',
  last_synced_at TIMESTAMPTZ, created_by_id BIGINT, created_by_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(company_id, provider, connection_name)
);

CREATE TABLE IF NOT EXISTS public.calendar_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  title TEXT NOT NULL, description TEXT, starts_at TIMESTAMPTZ NOT NULL, ends_at TIMESTAMPTZ,
  event_type TEXT DEFAULT 'MEETING', status TEXT NOT NULL DEFAULT 'SCHEDULED', created_by_id BIGINT, created_by_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_suppliers_company ON public.suppliers(company_id);
CREATE INDEX IF NOT EXISTS idx_purchase_orders_company ON public.purchase_orders(company_id, status);
CREATE INDEX IF NOT EXISTS idx_invoices_company ON public.invoices(company_id, status, due_date);
CREATE INDEX IF NOT EXISTS idx_support_tickets_company ON public.support_tickets(company_id, status, priority);
CREATE INDEX IF NOT EXISTS idx_projects_company ON public.projects(company_id, status);
CREATE INDEX IF NOT EXISTS idx_calendar_events_company ON public.calendar_events(company_id, starts_at);

