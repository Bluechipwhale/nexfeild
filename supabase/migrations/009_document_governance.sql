-- Additive document-governance records for the NexFieldForce ERP/CRM suite.
-- File binaries remain in approved object storage; this table stores tenant-safe metadata only.

CREATE TABLE IF NOT EXISTS public.document_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT 'GENERAL',
  description TEXT,
  owner_name TEXT,
  storage_path TEXT,
  retention_until DATE,
  status TEXT NOT NULL DEFAULT 'ACTIVE',
  created_by_id BIGINT,
  created_by_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_document_records_company
  ON public.document_records(company_id, category, status, retention_until);

ALTER TABLE public.document_records ENABLE ROW LEVEL SECURITY;
