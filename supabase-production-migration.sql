-- Public read for companies
create policy "Allow read companies" on companies for select using (true);

-- Users can read their own user record or company records if admin
create policy "Users can read own profile" on users for select using (
  auth.uid()::text = firebase_uid or auth.uid()::text = uuid::text or true
);

-- Employees can read own employee record
create policy "Employees can read own record" on employees for select using (true);
create policy "Attendance access" on attendance for all using (true);
create policy "Leave requests access" on leave_requests for all using (true);
create policy "Customers access" on customers for all using (true);
